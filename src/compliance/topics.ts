// Security topics: the common layer between Keelson's checks and compliance
// frameworks. Each check is listed under the topics it gives evidence for, and
// each framework's controls name topics (and, where a topic is too broad, single
// checks). A new framework then needs only its controls; a new check needs only
// its topics. `test/compliance.test.ts` fails when a check is in no topic and
// isn't listed in NO_TOPIC, or when a topic names a check that doesn't exist.

